"""Generate the per-anchor provenance table from the graph builder.

    python3 -I tools/build_provenance.py

Every graph node gets exactly one row. A row names a real resolution site: a
canon row that cites the work, a primary-text chapter row that names the node,
a research-report row that quotes the label, or the declaration line in
`tools/build_graph.py` for a locally defined derived term. Nothing is inferred
from a label's words. The generated file is checked by `validate_canon.py`.
"""
from __future__ import annotations

import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
REFS = ROOT / "skills" / "quorum" / "references"
BUILDER = ROOT / "tools" / "build_graph.py"
OUT = REFS / "anchor-provenance.md"
sys.path.insert(0, str(ROOT / "skills" / "quorum" / "scripts"))
import graph_walk  # noqa: E402

HEADER = """# Anchor provenance (generated)

Generated by `tools/build_provenance.py` from `tools/build_graph.py` and the
checked-in reference files. Every node in `anchor-graph.md` has exactly one
row. `Kind` is `cited` when a canon row, a primary-text chapter row or a
research-report row names the anchor, and `derived` when the term is defined
locally by the graph builder. A `derived` row still names a real declaration
line; it is not an external citation and is never presented as one.
`scripts/validate_canon.py` refuses uncovered or dangling rows. Do not edit.

| Node | Kind | Cluster | Resolution site |
|---|---|---|---|
"""


def declaration_lines() -> dict[str, int]:
    rows = {}
    for number, line in enumerate(BUILDER.read_text(encoding="utf-8").splitlines(), 1):
        match = re.match(r'^\s*"([a-z0-9_]+)\|', line)
        if match:
            rows.setdefault(match.group(1), number)
    return rows


def resolution(node: str, label: str) -> tuple[str, str]:
    canon = (REFS / "canon.md").read_text(encoding="utf-8")
    for number, line in enumerate(canon.splitlines(), 1):
        if line.startswith("| ") and label in line and "http" in line:
            return "cited", f"canon.md:{number}"
    for name in ("primary-texts.md", "research-report.md", "critic-panel.md"):
        text = (REFS / name).read_text(encoding="utf-8")
        for number, line in enumerate(text.splitlines(), 1):
            if line.startswith("| ") and (f"`{node}`" in line or label in line):
                return "cited", f"{name}:{number}"
    return "derived", f"tools/build_graph.py:{declaration_lines().get(node, 0)}"


def main() -> int:
    graph = graph_walk.parse(graph_walk.GRAPH_PATH)
    lines = [HEADER.rstrip("\n")]
    kinds = {"cited": 0, "derived": 0}
    for node in sorted(graph.labels):
        label = graph.labels[node].replace("|", "/")
        kind, site = resolution(node, label)
        kinds[kind] += 1
        lines.append(f"| `{node}` | {kind} | {graph.cluster_of[node] or 'UNASSIGNED'} | {site} |")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(json.dumps({"wrote": str(OUT), "rows": len(graph.labels), **kinds}, sort_keys=True))
    return 0 if kinds["cited"] > 0 and kinds["cited"] + kinds["derived"] == len(graph.labels) else 1


if __name__ == "__main__":
    sys.exit(main())
