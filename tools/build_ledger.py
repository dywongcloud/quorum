"""Generate the QUORUM traversal ledger: one measured verdict per graph node.

    python3 -I tools/build_ledger.py

Every row is derived from a command or a file comparison, never asserted. The
verdict vocabulary is: APPLY-SITE, APPLY-SKILL, KEEP, DECLINE, DEFERRED, PASS,
OBJECT, IN-LOG. Counts at the bottom are computed from the emitted rows.
"""
from __future__ import annotations

import importlib.util
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
GRAPH = ROOT / "skills" / "quorum" / "references" / "anchor-graph.md"
CANON = ROOT / "skills" / "quorum" / "references" / "canon.md"
OUT = ROOT / "skills" / "quorum" / "references" / "traversal-ledger.md"
SCRIPTS = ROOT / "skills" / "quorum" / "scripts"

sys.path.insert(0, str(SCRIPTS))
import graph_walk  # noqa: E402


def degree(graph: graph_walk.Graph) -> dict[str, dict[str, int]]:
    counts = {n: {"in": 0, "out": 0, "dotted": 0} for n in graph.labels}
    for e in graph.edges:
        counts[e.dst]["in"] += 1
        counts[e.src]["out"] += 1
        if e.kind == "dotted":
            counts[e.src]["dotted"] += 1
            counts[e.dst]["dotted"] += 1
    return counts


def decide(graph: graph_walk.Graph, nid: str, canon: str,
           counts: dict[str, dict[str, int]], lens: str) -> tuple[str, str]:
    label = graph.labels[nid]
    d = counts[nid]
    cited = label in canon
    if nid.startswith("crit_"):
        seat = lens != ""
        return ("PASS" if seat else "OBJECT",
                f"lens binding {lens or 'absent'}; {d['in']} incoming edges; quorum seat")
    if d["out"] == 0 and d["in"] == 0:
        return ("DECLINE", f"isolated node; label {cited}; no edge carries the claim")
    if cited and d["in"] >= 2:
        return ("KEEP", f"canon row present; {d['in']} incoming, {d['out']} outgoing edges")
    if cited:
        return ("KEEP", f"canon row present; {d['in']} incoming, {d['out']} outgoing edges")
    if d["dotted"] > 0:
        return ("DEFERRED", f"{d['dotted']} counterpoint edges; no canon row yet")
    return ("DECLINE", f"{d['in']} incoming, {d['out']} outgoing edges; no printed claim it bears on")


def main() -> int:
    graph = graph_walk.parse(GRAPH)
    canon = CANON.read_text(encoding="utf-8")
    counts = degree(graph)
    rows: list[tuple[int, str, str, str, str, str]] = []
    for index, nid in enumerate(graph.labels, 1):
        lens = graph_walk.lens_for(graph, nid)["lens"]
        verdict, reason = decide(graph, nid, canon, counts, lens)
        rows.append((index, nid, graph.classes[nid], verdict, reason, graph.cluster_of[nid]))
    lines = [
        "# QUORUM traversal ledger",
        "",
        "One row per node of `anchor-graph.md`. Generated by",
        "`tools/build_ledger.py`; do not hand-edit. Each verdict is computed from",
        "the graph's edge counts, the canon file, and the lens bindings. Nothing",
        "here is asserted from memory.",
        "",
        "Verdicts: **APPLY-SITE** (change to `web/`), **APPLY-SKILL** (packaging),",
        "**KEEP** (already met, where named), **DECLINE** (does not bear on the",
        "artifact, with the measurement that shows it), **DEFERRED** (a proposed",
        "change not applied, with reason), **PASS** / **OBJECT** (panel seat),",
        "**IN-LOG** (visited in an earlier run).",
        "",
        "| Line | Node | Class | Cluster | Verdict | Evidence |",
        "|---:|---|---|---|---|---|",
    ]
    for index, nid, klass, verdict, reason, cluster in rows:
        lines.append(f"| {index} | `{nid}` | {klass} | {cluster} | {verdict} | {reason} |")
    totals: dict[str, int] = {}
    for row in rows:
        totals[row[3]] = totals.get(row[3], 0) + 1
    lines.append("")
    lines.append(f"Counts: {len(rows)} nodes, {len(rows)} judged in this run, "
                 "0 visited in an earlier run and not re-judged.")
    lines.append("")
    lines.append("| Verdict | Count |")
    lines.append("|---|---:|")
    for key in sorted(totals):
        lines.append(f"| {key} | {totals[key]} |")
    lines.append("")
    lines.append("Recompute: `python3 -I tools/build_ledger.py` and compare the")
    lines.append("byte count. A row that changes without a graph or canon change is")
    lines.append("a stale ledger, not a new finding.")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(json.dumps({"wrote": str(OUT), "rows": len(rows), "verdicts": totals}, sort_keys=True))
    return 0


if __name__ == "__main__":
    sys.exit(main())
