"""Generate the QUORUM Panel Reports section from the filed verdict files.

    python3 -I tools/build_panel_report.py

A verdict is a file. This script reads panel/R1 and panel/R2, collects the
required roster from graph_walk.py, and transcribes each filed verdict into a
rigid Markdown table. It never invents a verdict: a missing seat is recorded
as NOT REPORTED. It writes analysis/panel-report.md and splices that table
into QUORUM-LOG.md between the PANEL markers. All output is deterministic.
"""
from __future__ import annotations

import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SCRIPTS = ROOT / "skills" / "quorum" / "scripts"
PANEL = ROOT / "panel"
OUT = ROOT / "analysis" / "panel-report.md"
LOG = ROOT / "QUORUM-LOG.md"
START = "<!-- PANEL:START -->"
END = "<!-- PANEL:END -->"
sys.path.insert(0, str(SCRIPTS))
import graph_walk  # noqa: E402

FIELDS = ("Anchor used", "Observed", "Verdict", "Requested change",
          "Command", "Dispatch id", "Session id", "Statements of meaning",
          "Designer questions", "Critic questions", "Opinions", "Andon pulled")


def parse_verdict(text: str) -> dict[str, str]:
    found: dict[str, str] = {}
    for field in FIELDS:
        match = re.search(r"^\s*" + re.escape(field) + r"\s*[:=]\s*(.+?)\s*$",
                          text, flags=re.MULTILINE | re.IGNORECASE)
        found[field] = match.group(1).strip() if match else ""
    return found


def clean(text: str) -> str:
    return text.replace("|", "/").replace("\n", " ").strip()


def main() -> int:
    graph = graph_walk.parse(graph_walk.GRAPH_PATH)
    roster = list(graph_walk.roster(graph, "fail-closed")["required_seats"])
    lines = ["# QUORUM panel report (generated)", "",
             "Generated by `tools/build_panel_report.py` from the verdict files.",
             "A missing file is NOT REPORTED, never PASS. Do not hand-edit.", ""]
    summary = []
    for round_name in ("R1", "R2", "R3", "R4"):
        folder = PANEL / round_name
        lines.append(f"## Round {round_name}")
        lines.append("")
        lines.append("| Seat | Anchor used | Observed | Verdict | Requested change | Words |")
        lines.append("|---|---|---|---|---|---:|")
        reported = 0
        passing = 0
        objecting = 0
        for seat in roster:
            target = folder / f"{seat}.md"
            if not target.is_file():
                lines.append(f"| `{seat}` | - | - | NOT REPORTED | - | 0 |")
                continue
            text = target.read_text(encoding="utf-8", errors="replace")
            words = len(text.split())
            if words < 20:
                lines.append(f"| `{seat}` | - | - | NOT REPORTED | - | {words} |")
                continue
            verdict = parse_verdict(text)
            v = verdict["Verdict"].upper()
            if "PASS" in v:
                passing += 1
            elif "OBJECT" in v:
                objecting += 1
            reported += 1
            lines.append("| `" + seat + "` | " + clean(verdict["Anchor used"] or "-") +
                         " | " + clean(verdict["Observed"] or "-") + " | " +
                         clean(v or "-") + " | " +
                         clean(verdict["Requested change"] or "-") + " | " + str(words) + " |")
        lines.append("")
        lines.append(f"Quorum certificate: {reported}/{len(roster)} seats reporting; "
                     f"PASS {passing}, OBJECT {objecting}, "
                     f"quorum {'true' if reported == len(roster) else 'false'}.")
        lines.append("")
        summary.append({"round": round_name, "reported": reported,
                        "required": len(roster), "pass": passing,
                        "object": objecting, "quorum": reported == len(roster)})
    lines.append("## Saturation re-collection of R2")
    lines.append("")
    lines.append("`collect_panel.py panel/R2 --roster fail-closed --json` is run twice at")
    lines.append("final state. An identical stdout digest across the two runs means no seat")
    lines.append("changed, no Andon opened and no Frontier item became OPEN. This is S3.")
    lines.append("")
    lines.append("## Unrendered evidence")
    lines.append("")
    lines.append("`unrendered`: true. The gm browser verb in this environment is headful-only")
    lines.append("and needs a desktop session; no rendered screenshot was judged. Contrast,")
    lines.append("target sizes and figure counts were computed from source by")
    lines.append("`tools/measure_web.py` and recorded in `analysis/web-measurements.json`.")
    lines.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    log = LOG.read_text(encoding="utf-8")
    if START in log and END in log:
        head, rest = log.split(START, 1)
        _, tail = rest.split(END, 1)
        log = head + START + "\n" + "\n".join(lines) + "\n" + END + tail
        LOG.write_text(log, encoding="utf-8")
    print(json.dumps({"wrote": str(OUT), "rounds": summary}, sort_keys=True))
    return 0


if __name__ == "__main__":
    sys.exit(main())
